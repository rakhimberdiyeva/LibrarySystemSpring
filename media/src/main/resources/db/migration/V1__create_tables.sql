CREATE TABLE IF NOT EXISTS media_covers(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    filename TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS media_docs(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    filename TEXT NOT NULL
);